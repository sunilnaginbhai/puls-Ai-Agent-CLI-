import { mkdtempSync, mkdirSync, rmSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';

// Preload before test imports: even an accidentally eager settings import must
// resolve into disposable storage, never the developer's actual profile.
const temporaryRoot = mkdtempSync(path.join(os.tmpdir(), 'puls-ai-test-environment-'));
const workspace = path.join(temporaryRoot, 'workspace');
mkdirSync(workspace);
process.env.PULS_HOME = temporaryRoot;
process.env.PULS_AI_WORKSPACE = workspace;
for (const name of [
    'PULS_API_KEY', 'GROQ_API_KEY', 'OPENAI_API_KEY', 'GOOGLE_API_KEY',
    'GOOGLE_GENERATIVE_AI_API_KEY', 'LANGCHAIN_API_KEY', 'LANGSMITH_API_KEY',
    'PULS_MODEL', 'PULS_PROVIDER', 'PULS_REQUEST_TIMEOUT_MS',
]) delete process.env[name];
process.env.LANGCHAIN_TRACING_V2 = 'false';
process.env.LANGSMITH_TRACING = 'false';

process.once('exit', () => {
    // Only remove the exact absolute directory generated by mkdtemp above.
    const relative = path.relative(path.resolve(os.tmpdir()), path.resolve(temporaryRoot));
    if (!relative.startsWith('puls-ai-test-environment-') || relative.includes(path.sep)) return;
    try { rmSync(temporaryRoot, { recursive: true, force: true }); }
    catch { /* An external file lock may defer cleanup; never touch another path. */ }
});
